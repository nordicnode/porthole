//! Companion automation configs: Unpackerr, Janitorr, and guided
//! setups for the ones Porthole can't fully wire (Cleanuparr,
//! Maintainerr, Tautulli, Jellystat, Wizarr, Kometa).
//!
//! Honest boundaries, like Bazarr in Phase 7:
//! - Automate what Porthole can verify (API keys it holds).
//! - Guide the rest with exact values (never fake automation).

/// Unpackerr env file: *arr URLs + API keys.
/// Porthole reads the keys from the *arr config.xml files.
pub fn unpackerr_env(sonarr_key: &str, radarr_key: &str, lidarr_key: Option<&str>) -> String {
    let mut out = format!(
        "# Generated by Porthole — Unpackerr *arr connections.\n\
         UN_SONARR_0_URL=http://sonarr:8989\n\
         UN_SONARR_0_API_KEY={sonarr_key}\n\
         UN_RADARR_0_URL=http://radarr:7878\n\
         UN_RADARR_0_API_KEY={radarr_key}\n"
    );
    if let Some(k) = lidarr_key {
        out.push_str(&format!(
            "UN_LIDARR_0_URL=http://lidarr:8686\nUN_LIDARR_0_API_KEY={k}\n"
        ));
    }
    out
}

/// Janitorr application.yml — ALWAYS starts with dry-run: true.
/// (Research trap #234: misconfigured expiration + bad watch data =
/// mass deletion. Dry-run first, always.)
pub fn janitorr_config() -> String {
    String::from(
        "# Generated by Porthole — Janitorr starts in DRY-RUN.\n\
         # It logs what WOULD be deleted. Review, then set dry-run: false.\n\
         dry-run: true\n\
         \n\
         # Check daily at 2 AM.\n\
         media-cleanup-schedule: \"0 0 2 * * ?\"\n\
         tag-cleanup-schedule: \"0 0 3 * * ?\"\n\
         \n\
         # Conservative: only clean what hasn't been watched in a year,\n\
         # and only when disk is over 90% full.\n\
         # (Tune in Janitorr's UI after you've reviewed a dry-run.)\n\
         leaving-soon: 400d\n\
         \n\
         # Never delete these, even if they match.\n\
         exclusion-tags:\n\
         \x20\x20 - janitorr_keep\n\
         \x20\x20 - janitor-keep\n\
         \n\
         # Whole-show handling OFF (treats a series as one unit — dangerous).\n\
         whole-tv-show: false\n",
    )
}

/// Guided steps for Cleanuparr (its config schema isn't stable enough
/// to pre-seed safely; Porthole shows the exact values).
