#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unpackerr_env_has_keys() {
        let env = unpackerr_env("skey", "rkey", Some("lkey"));
        assert!(env.contains("UN_SONARR_0_API_KEY=skey"));
        assert!(env.contains("UN_RADARR_0_API_KEY=rkey"));
        assert!(env.contains("UN_LIDARR_0_API_KEY=lkey"));
    }

    #[test]
    fn janitorr_starts_dry_run() {
        let cfg = janitorr_config();
        assert!(cfg.contains("dry-run: true"));
        assert!(cfg.contains("whole-tv-show: false"));
    }

    #[test]
    fn kometa_config_is_plex_only() {
        let cfg = kometa_config();
        assert!(cfg.contains("http://plex:32400"));
        assert!(cfg.contains("YOUR_TMDB_KEY_HERE"));
    }
}
