#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rclone_conf_has_crypt() {
        let conf = render_rclone_conf(&CloudBackend::GoogleDrive, "secret123");
        assert!(conf.contains("[crypt]"));
        assert!(conf.contains("type = crypt"));
        assert!(conf.contains("filename_encryption = standard"));
        assert!(conf.contains("directory_name_encryption = true"));
        assert!(conf.contains("type = drive"));
        // Never commit hints.
        assert!(conf.contains("DO NOT commit"));
    }

    #[test]
    fn mount_service_has_vfs_presets() {
        let svc = render_mount_service(Path::new("/install"), 20);
        assert!(svc.contains("--vfs-cache-mode full"));
        assert!(svc.contains("--allow-other"));
        assert!(svc.contains("--vfs-cache-max-size 20G"));
        assert!(svc.contains("--buffer-size 64M"));
    }

    #[test]
    fn mover_has_safety_flags() {
        let script = render_mover_script(Path::new("/install"));
        assert!(script.contains("flock -n"));
        assert!(script.contains("--min-age 15m"));
        assert!(script.contains("--delete-empty-src-dirs"));
        assert!(script.contains("--drive-stop-on-upload-limit"));
        assert!(script.contains("--max-transfer 700G"));
        assert!(script.contains("--bwlimit"));
    }

    #[test]
    fn backend_blurbs_are_honest() {
        assert!(CloudBackend::GoogleDrive.blurb().contains("750 GB/day"));
        assert!(CloudBackend::Dropbox.blurb().contains("3 TB"));
    }
}
